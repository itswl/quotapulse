/**
 * English messages: the source of truth for the message keys.
 *
 * Every other dictionary is typed against this one, so a key that is missing from a
 * translation fails `npm run typecheck` instead of showing up as an English string in a
 * Chinese interface. Keys are namespaced by the part of the page they belong to.
 *
 * Placeholders are `{name}`; a message that depends on a count is a `Plural` and the
 * `count` parameter picks the form (exactly one → `one`, anything else → `other`).
 * Chinese has no plural forms, so its dictionary uses plain strings there.
 */

